def process_all_chapters():
    """处理所有需要修复的篇章"""
    chapters = [f"chapter_{i:02d}.json" for i in range(3, 32)]

    for chapter_file in chapters:
        filepath = os.path.join(OUTPUT_DIR, chapter_file)
        if not os.path.exists(filepath):
            print(f"File not found: {filepath}")
            continue

        with open(filepath, 'r', encoding='utf-8') as f:
            data = json.load(f)

        # 为每个段落生成翻译
        for para in data['paragraphs']:
            content = para['content']
            # 生成翻译
            translation = simple_translate(content)
            # 如果翻译和原文基本相同，说明需要人工处理
            if translation == content:
                # 尝试更激进的转换
                translation = content + "（待翻译）"
            para['translation'] = translation

        # 保存
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        print(f"Processed {chapter_file}")

if __name__ == "__main__":
    process_all_chapters()
